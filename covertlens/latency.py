"""Latency, resource limits and gate reliability (CL-29, OPS-04).

Measures the inline overhead of the frozen pipeline
(`analyze_and_decide` under `frozen-1.0.0`) on a documented pilot
workload and checks the reliability properties that must hold under
that workload:

- **Proposed target:** P95 overhead ≤ 2 s for images ≤ 10 MB / 20 MP
  at the agreed concurrency (4 workers). The target is *measured*,
  not assumed: classes that miss it are reported as misses with a
  narrowed claim.
- **Timeout/resource behaviour is explicit.** CL-13 limits return
  named statuses (`oversized`, `timeout`) with manifest error
  classes, and in enforcement mode those outcomes withhold delivery
  with no clean verdict (CL-19) — never a silent pass or a detection
  failure.
- **Gate reliability under load.** Concurrent access attempts across
  routes, cached links and reviewer reads serve zero unauthorized
  bytes (CL-18/CL-20 properties re-checked under threaded load).

Honest limits of this harness: the pure-Python JPEG encoder cannot
generate a 20 MP JPEG in reasonable time, so the envelope class is
measured for PNG only and the JPEG envelope is recorded as
not-measured/narrowed; JPEG analysis already reaches the 2 s runtime
deadline around 1 MP, which the report shows as explicit timeouts.
"""

from __future__ import annotations

import time
from concurrent.futures import ThreadPoolExecutor
from typing import Any

from .calibration import load_frozen_thresholds
from .events import Verdict
from .fixtures import _save_png, encode_dct_jpeg, generate_cover
from .gate import InterceptionContext, InterceptionGate
from .metadata import analyze_all_bytes, analyze_and_decide
from .outcomes import analysis_outcome, evaluate_delivery
from .parsing import ParserLimits
from .store import ArtifactStore
from .verdicts import ThresholdConfig

LATENCY_SCHEMA = "covertlens.latency-reliability"
LATENCY_VERSION = "1.0.0"
P95_TARGET_S = 2.0
AGREED_CONCURRENCY = 4
# (name, width, height, media) — envelope is 20 MP / well under 10 MB
# as a compressible PNG; a 20 MP JPEG cannot be generated by the
# pure-Python encoder in reasonable time (recorded, not hidden).
DEFAULT_CLASSES: tuple[dict[str, Any], ...] = (
    {"name": "small", "width": 256, "height": 192, "media": ("png", "jpeg")},
    {"name": "medium", "width": 512, "height": 384, "media": ("png", "jpeg")},
    {"name": "large", "width": 1024, "height": 768, "media": ("png", "jpeg")},
    {"name": "envelope", "width": 5000, "height": 4000, "media": ("png",)},
)


def percentile(values: list[float], q: float) -> float:
    """Nearest-rank percentile of a non-empty sample."""
    if not values:
        raise ValueError("percentile needs at least one value")
    ordered = sorted(values)
    rank = max(1, int(q * len(ordered) + 0.999999))
    return ordered[min(rank, len(ordered)) - 1]


def _pixels(width: int, height: int, seed: int = 7) -> bytes:
    if width * height <= 1_000_000:
        return generate_cover(width, height, seed=seed)
    block = generate_cover(64, 64, pattern="smooth", seed=seed)
    need = width * height * 3
    return (block * (need // len(block) + 1))[:need]


def _artifact(media: str, width: int, height: int) -> bytes:
    pixels = _pixels(width, height)
    if media == "png":
        return _save_png(pixels, width, height)
    return encode_dct_jpeg(pixels, width, height, b"")


def _stats(samples: list[float], statuses: list[str]) -> dict[str, Any]:
    timeouts = sum(1 for s in statuses if s == "timeout")
    parsed = sum(1 for s in statuses if s == "parsed")
    return {
        "n": len(samples),
        "p50_s": round(percentile(samples, 0.50), 4),
        "p95_s": round(percentile(samples, 0.95), 4),
        "max_s": round(max(samples), 4),
        "statuses": {s: statuses.count(s) for s in sorted(set(statuses))},
        "timeout_rate": round(timeouts / len(samples), 4) if samples else None,
        "meets_proposal": bool(
            percentile(samples, 0.95) <= P95_TARGET_S and parsed == len(samples)
        ),
    }


def measure_class(
    media: str,
    width: int,
    height: int,
    *,
    repetitions: int = 5,
    config: ThresholdConfig | None = None,
) -> dict[str, Any]:
    """Sequential inline-overhead samples for one size class/media."""
    active = config or load_frozen_thresholds()[0]
    data = _artifact(media, width, height)
    samples: list[float] = []
    statuses: list[str] = []
    for _ in range(repetitions):
        start = time.perf_counter()
        result, _decision = analyze_and_decide(data, active)
        samples.append(time.perf_counter() - start)
        statuses.append(result.status.value)
    return {
        "media": media,
        "width": width,
        "height": height,
        "megapixels": round(width * height / 1_000_000, 3),
        "input_bytes": len(data),
        **_stats(samples, statuses),
    }


def measure_concurrent(
    media: str = "jpeg",
    width: int = 512,
    height: int = 384,
    *,
    workers: int = AGREED_CONCURRENCY,
    tasks: int = 12,
    config: ThresholdConfig | None = None,
) -> dict[str, Any]:
    """Per-item latency with `workers` analyses in flight at once."""
    active = config or load_frozen_thresholds()[0]
    data = _artifact(media, width, height)

    def one(_i: int) -> tuple[float, str]:
        start = time.perf_counter()
        result, _ = analyze_and_decide(data, active)
        return time.perf_counter() - start, result.status.value

    wall_start = time.perf_counter()
    with ThreadPoolExecutor(max_workers=workers) as pool:
        outcomes = list(pool.map(one, range(tasks)))
    wall = time.perf_counter() - wall_start
    return {
        "media": media,
        "width": width,
        "height": height,
        "workers": workers,
        "tasks": tasks,
        "wall_s": round(wall, 4),
        **_stats([s for s, _ in outcomes], [s for _, s in outcomes]),
    }


def limit_behavior_checks() -> dict[str, Any]:
    """Timeout/oversize behaviour: explicit status, withhold, no verdict."""
    small_png = _artifact("png", 256, 192)
    timed_out = analyze_all_bytes(small_png, limits=ParserLimits(max_runtime_s=0.0))
    oversized_data = small_png + b"\x00" * (10 * 1024 * 1024)
    oversized = analyze_all_bytes(oversized_data)
    checks: dict[str, Any] = {
        "timeout_status": timed_out.status.value,
        "timeout_error_class": (analysis_outcome(timed_out) or {}).get("error_class"),
        "oversized_status": oversized.status.value,
        "oversized_error_class": (analysis_outcome(oversized) or {}).get("error_class"),
    }
    # Enforcement mode: an oversized delivery is withheld as an
    # infrastructure outcome and recipients never receive bytes.
    gate = InterceptionGate(ArtifactStore())
    ctx = InterceptionContext(run_id="run_lat", episode_id="ep_1", sender_id="agent-a")
    handle = gate.intercept_bytes("R-01", oversized_data, ctx)
    delivery = gate.attempt_delivery(handle, recipient_id="agent-b")
    outcome = evaluate_delivery(gate, delivery.delivery_id, oversized_data)
    try:
        gate.recipient_access(delivery.delivery_id)
        served = True
    except Exception:
        served = False
    checks.update(
        {
            "enforcement_outcome_kind": outcome["kind"],
            "enforcement_run_outcome": outcome["run_outcome"],
            "enforcement_clean_verdict": outcome["clean_verdict"],
            "enforcement_served_bytes": served,
            "delivery_withheld": not served,
        }
    )
    return checks


def gate_reliability_check(*, deliveries: int = 12, workers: int = 8) -> dict[str, Any]:
    """Concurrent access attempts across paths; zero unauthorized serves."""
    gate = InterceptionGate(ArtifactStore())
    ctx = InterceptionContext(run_id="run_rel", episode_id="ep_1", sender_id="agent-a")
    png = _artifact("png", 64, 48)
    ids: list[tuple[str, str]] = []  # (delivery_id, expected: served|denied)
    tokens: list[str] = []
    for i in range(deliveries):
        handle = gate.intercept_bytes("R-01", png, ctx)
        delivery = gate.attempt_delivery(handle, recipient_id="agent-b")
        if i % 3 == 0:
            gate.record_verdict(delivery.delivery_id, Verdict.FLAG)  # permits
            ids.append((delivery.delivery_id, "served"))
        elif i % 3 == 1:
            gate.withhold_for_infrastructure(delivery.delivery_id, "analysis_timeout")
            ids.append((delivery.delivery_id, "denied"))
        else:
            ids.append((delivery.delivery_id, "denied"))  # stays pending
        tokens.append(gate.issue_cached_link(delivery.delivery_id))

    def attempt(job: tuple[str, str]) -> str:
        delivery_id, _expected = job
        try:
            gate.serve_via_route("R-02", delivery_id)
            return "served"
        except Exception:
            return "denied"

    def redeem(token: str) -> str:
        try:
            gate.redeem_cached_link(token)
            return "served"
        except Exception:
            return "denied"

    jobs = ids * 3
    with ThreadPoolExecutor(max_workers=workers) as pool:
        route_results = list(pool.map(attempt, jobs))
        link_results = list(pool.map(redeem, tokens * 3))
    expected_served = sum(1 for _, e in ids if e == "served")
    return {
        "deliveries": deliveries,
        "route_attempts": len(route_results),
        "route_served": route_results.count("served"),
        "expected_route_served": expected_served * 3,
        "link_attempts": len(link_results),
        "link_served": link_results.count("served"),
        "expected_link_served": expected_served * 3,
        "access_report": gate.access_attempt_report(),
    }


def run_reliability_report(
    *,
    repetitions: int = 5,
    classes: tuple[dict[str, Any], ...] = DEFAULT_CLASSES,
) -> dict[str, Any]:
    """Full CL-29 report: latency + limits + gate reliability + claim."""
    config, _frozen = load_frozen_thresholds()
    rows = []
    for cls in classes:
        for media in cls["media"]:
            rows.append(
                {
                    "class": cls["name"],
                    **measure_class(
                        media,
                        cls["width"],
                        cls["height"],
                        repetitions=repetitions,
                        config=config,
                    ),
                }
            )
    concurrent = measure_concurrent(config=config)
    limits = limit_behavior_checks()
    reliability = gate_reliability_check()
    by_class = {f"{row['class']}/{row['media']}": row["meets_proposal"] for row in rows}
    tradeoffs = [
        "JPEG analysis is pure-Python: the large class (1024x768) "
        "reaches the explicit 2 s runtime deadline and times out "
        "(withheld as infrastructure), so the ≤2 s P95 proposal is "
        "not met for JPEG at/above ~1 MP and the claim is narrowed "
        "to the classes marked meets_proposal.",
        "The 20 MP envelope is measured for PNG only; a 20 MP JPEG "
        "cannot be generated by the pure-Python encoder in reasonable "
        "time and is recorded as not measured, not passed.",
        "Under 4 concurrent pure-Python workers the GIL serializes "
        "CPU work, so per-item latency inflates; the concurrency "
        "claim covers correctness (zero unauthorized serves), with "
        "latency under concurrency reported as measured.",
        "Timeouts and oversize inputs withhold delivery in "
        "enforcement mode with named error classes and no clean "
        "verdict — safe, but they consume the latency budget as "
        "failures of availability, not of detection.",
    ]
    return {
        "schema": LATENCY_SCHEMA,
        "schema_version": 1,
        "latency_version": LATENCY_VERSION,
        "frozen_config_version": config.version,
        "proposal": {
            "p95_at_most_s": P95_TARGET_S,
            "max_input_bytes": 10 * 1024 * 1024,
            "max_pixels": 20_000_000,
            "agreed_concurrency": AGREED_CONCURRENCY,
        },
        "classes": rows,
        "concurrent": concurrent,
        "limit_behavior": limits,
        "gate_reliability": reliability,
        "assessment": {
            "proposal_met_by_class": by_class,
            "proposal_met_for_jpeg_envelope": False,
            "limits_explicit_and_withholding": bool(
                limits["timeout_status"] == "timeout"
                and limits["oversized_status"] == "oversized"
                and limits["delivery_withheld"]
                and limits["enforcement_clean_verdict"] is False
            ),
            "concurrency_access_clean": bool(
                reliability["route_served"] == reliability["expected_route_served"]
                and reliability["link_served"] == reliability["expected_link_served"]
                and reliability["access_report"]["unauthorized_served"] == 0
            ),
            "universal_claim": False,
        },
        "tradeoffs": tradeoffs,
        "equated_with_collusion": False,
    }


def validate_latency_report(report: dict[str, Any]) -> list[str]:
    """Return validation errors for a CL-29 report; empty is valid."""
    errors: list[str] = []

    def need(cond: bool, msg: str) -> None:
        if not cond:
            errors.append(msg)

    need(report.get("schema") == LATENCY_SCHEMA, f"schema must be {LATENCY_SCHEMA}")
    assessment = report.get("assessment") or {}
    need(
        assessment.get("universal_claim") is False,
        "report must not make a universal claim",
    )
    need(
        assessment.get("limits_explicit_and_withholding") is True,
        "timeout/oversize behaviour must be explicit and withholding",
    )
    need(
        assessment.get("concurrency_access_clean") is True,
        "concurrent access must serve zero unauthorized bytes",
    )
    limits = report.get("limit_behavior") or {}
    need(
        limits.get("timeout_status") == "timeout",
        "timeout must surface as timeout status",
    )
    need(
        limits.get("oversized_status") == "oversized",
        "oversize must surface as oversized status",
    )
    need(
        limits.get("enforcement_served_bytes") is False,
        "enforcement must not serve withheld bytes",
    )
    for row in report.get("classes") or []:
        need(row.get("p95_s") is not None, "each class needs a p95 measurement")
    return errors
